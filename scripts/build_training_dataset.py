"""Training-dataset assembly entry point.

Usage (from project root):
    python scripts/build_training_dataset.py

For each turbine, joins the resampled hourly production (data/processed/
turbine_<id>_hourly.parquet) with weather features fetched "as if a
forecast had been issued 24h/48h earlier" (src/features/weather_features.py
+ src/weather/client.py), adds lag and physical/time features, drops
untrustworthy target rows (is_gap / curtailment_suspected), and writes:

  - data/processed/turbine_<id>_train.parquet
  - outputs/dataset/dataset_summary.md
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data import schema as data_schema
from src.features import build, schema


def write_summary(all_stats: list[dict], datasets: dict) -> None:
    lines = ["# Training dataset assembly summary", "", "Generated by `scripts/build_training_dataset.py`.", ""]
    for stats in all_stats:
        tid = stats["turbine_id"]
        df = datasets[tid]
        lines += [
            f"## Turbine {tid}",
            "",
            f"- Final training rows (both lead groups combined): {len(df):,}",
            f"- Date range: {df['timestamp'].min()} -> {df['timestamp'].max()}",
            "",
            "| lead_hours | full-coverage start | hours seen | excluded (is_gap) | excluded (curtailment) | kept | missing lag_power_t0 | weather sources |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for lead_hours, s in stats["by_lead"].items():
            sources = ", ".join(f"{k}={v}" for k, v in s["weather_source_counts"].items())
            lines.append(
                f"| {lead_hours} | {s['coverage_start']} | {s['n_total_hours']:,} | {s['n_excluded_gap']:,} | "
                f"{s['n_excluded_curtailment']:,} | {s['n_kept']:,} | {s['n_missing_lag_power_t0']:,} | {sources} |"
            )
        lines.append("")
        lines.append(f"Feature columns: `{', '.join(schema.FEATURE_COLUMNS)}`")
        lines.append(f"Target column: `{schema.TARGET_COLUMN}`")
        lines.append("")
        lines.append(f"Saved to `data/processed/{schema.TRAIN_PARQUET_TEMPLATE.format(turbine_id=tid)}`")
        lines.append("")

    report_path = schema.DATASET_OUTPUT_DIR / "dataset_summary.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Summary written to {report_path}")


def main() -> None:
    schema.DATASET_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    all_stats = []
    datasets = {}
    for turbine_id in data_schema.RAW_FILES:
        print(f"\n=== Assembling training dataset for turbine {turbine_id} ===")
        dataset, stats = build.assemble_turbine_dataset(turbine_id)
        datasets[turbine_id] = dataset
        all_stats.append(stats)

        out_path = data_schema.PROCESSED_DATA_DIR / schema.TRAIN_PARQUET_TEMPLATE.format(turbine_id=turbine_id)
        dataset.to_parquet(out_path, index=False)
        print(f"rows={len(dataset):,} -> saved {out_path}")
        for lead_hours, s in stats["by_lead"].items():
            print(
                f"  lead={lead_hours}h: total={s['n_total_hours']:,} "
                f"excluded_gap={s['n_excluded_gap']:,} excluded_curtailment={s['n_excluded_curtailment']:,} "
                f"kept={s['n_kept']:,} missing_lag={s['n_missing_lag_power_t0']:,} "
                f"sources={s['weather_source_counts']}"
            )

    write_summary(all_stats, datasets)


if __name__ == "__main__":
    main()
